#include "AppImageUpdate.h"
#include <QCoreApplication>
#include <QFileInfo>
#include <QResource>
#include <QTimer>
#include <cstdio>

static int exitDuringDownload(QCoreApplication &app) {
    QTimer poll;
    QObject::connect(&poll, &QTimer::timeout, &app, [&] {
        if (QFileInfo::exists(qEnvironmentVariable("DRINK_TEST_BLOCKING")))
            app.exit(0);
    });
    poll.start(20);
    return app.exec(); // Destroy the updater during its download.
}

static int testRetryAndRestart(QCoreApplication &app,
                               kde::AppImageUpdate &update) {
    bool retried = false;
    int checks = 0;
    QObject::connect(&update, &kde::AppImageUpdate::restartRequested, &app,
                     [&](const QString &image) {
                         app.exit(retried && checks == 2 &&
                                          image ==
                                              qEnvironmentVariable("APPIMAGE")
                                      ? 0
                                      : 1);
                     });
    QObject::connect(&update, &kde::AppImageUpdate::changed, &app, [&] {
        if (update.checking()) {
            ++checks;
            update.check(); // Repeated clicks share a single check.
        } else if (update.ready()) {
            update.check();
            update.restartIfReady();
        } else if (!retried && update.menuText().contains("Retry")) {
            retried = true;
            QTimer::singleShot(0, &update, &kde::AppImageUpdate::check);
        } else {
            std::fprintf(stderr, "Unexpected update status: %s\n",
                         qPrintable(update.menuText()));
            app.exit(1);
        }
    });
    update.restartIfReady();
    return app.exec();
}

// Execute the real QObject and embedded helper contract with an isolated
// resource collection containing only the test key generated by the driver.
int main(int argc, char **argv) {
    QCoreApplication app(argc, argv);
    app.setApplicationVersion("2025.01.01");
    if (app.arguments().size() != 3 ||
        !QResource::registerResource(app.arguments()[1]))
        return 1;
    kde::AppImageUpdate update;
    if (app.arguments()[2] == "disabled")
        return update.enabled() ? 1 : 0;
    if (!update.enabled())
        return 1;
    QTimer::singleShot(20000, &app, [&] { app.exit(1); });
    if (app.arguments()[2] == "cancel")
        return exitDuringDownload(app);
    return testRetryAndRestart(app, update);
}
