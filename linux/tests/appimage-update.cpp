#include "AppImageUpdate.h"
#include <QCoreApplication>
#include <QDebug>
#include <QFileInfo>
#include <QResource>
#include <QTimer>

static int exitDuringDownload() {
    QTimer poll;
    QObject::connect(&poll, &QTimer::timeout, &poll, [] {
        if (QFileInfo::exists(qEnvironmentVariable("DRINK_TEST_BLOCKING"))) {
            QCoreApplication::exit(0);
        }
    });
    poll.start(20);
    return QCoreApplication::exec(); // Destroy the updater during its download.
}

static int testRetryAndRestart(kde::AppImageUpdate &update) {
    bool retried = false;
    int checks = 0;
    QObject observer;
    QObject::connect(&update, &kde::AppImageUpdate::restartRequested, &observer,
                     [&](const QString &image) {
                         QCoreApplication::exit(
                             retried && checks == 2 &&
                                     image == qEnvironmentVariable("APPIMAGE")
                                 ? 0
                                 : 1);
                     });
    QObject::connect(&update, &kde::AppImageUpdate::changed, &observer, [&] {
        if (update.checking()) {
            ++checks;
            update.check(); // Repeated clicks share a single check.
        } else if (update.ready()) {
            update.check();
            update.restartIfReady();
        } else if (!retried && update.menuText().contains("Retry")) {
            retried = true;
            QTimer::singleShot(0, &update, &kde::AppImageUpdate::check);
        } else {
            qCritical().noquote()
                << "Unexpected update status:" << update.menuText();
            QCoreApplication::exit(1);
        }
    });
    update.restartIfReady();
    return QCoreApplication::exec();
}

// Execute the real QObject and embedded helper contract with an isolated
// resource collection containing only the test key generated by the driver.
int main(int argc, char **argv) {
    QCoreApplication app(argc, argv);
    QCoreApplication::setApplicationVersion("2025.01.01");
    const auto arguments = QCoreApplication::arguments();
    if (arguments.size() != 3 || !QResource::registerResource(arguments[1])) {
        return 1;
    }
    kde::AppImageUpdate update;
    if (arguments[2] == "disabled") {
        return update.enabled() ? 1 : 0;
    }
    if (!update.enabled()) {
        return 1;
    }
    QTimer::singleShot(20000, &app, [] { QCoreApplication::exit(1); });
    if (arguments[2] == "cancel") {
        return exitDuringDownload();
    }
    return testRetryAndRestart(update);
}
